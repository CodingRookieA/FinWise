def _title_value(html, label):
    """Extract text from a title / title-value pair."""
    m = re.search(
        r'<span>' + re.escape(label) + r'</span>.*?<div class="title-value">\s*(.*?)\s*</div>',
        html, re.DOTALL | re.IGNORECASE,
    )
    if not m:
        return None
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(1))).strip() or None


def get_td_fund_by_code(fund_code: str):
    fund_code = (fund_code or "").strip().upper()
    fund_id = TD_FUNDID_BY_CODE.get(fund_code)
    if fund_id is None:
        return None

    url = "https://www.td.com/ca/en/asset-management/funds/solutions/mutual-funds/fundcard"
    headers = {"User-Agent": "Mozilla/5.0"}
    params = {"fundId": str(fund_id)}

    r = requests.get(url, headers=headers, params=params, timeout=20)
    if r.status_code != 200:
        return None

    html = r.text

    # -- name --
    nm = re.search(r'data-fund-name="([^"]+)"', html)
    name = nm.group(1).replace('&#39;', "'") if nm else None

    # -- nav --
    pm = re.search(r'Price.*?\$\s*([0-9]+(?:\.[0-9]+)?)', html, re.IGNORECASE | re.DOTALL)
    nav = float(pm.group(1)) if pm else None

    # -- mer (inside info-copy span, not title-value) --
    mer = None
    mer_m = re.search(r'>MER\b.*?<div class="info-copy">\s*<span>\s*([0-9.]+)%', html, re.DOTALL)
    if mer_m:
        mer = float(mer_m.group(1))

    # -- performance (data-historic-perf JSON) --
    yr1 = yr3 = yr5 = None
    hp = re.search(r'data-historic-perf="([^"]+)"', html)
    if hp:
        perf_json = hp.group(1).replace('&#34;', '"').replace('&amp;', '&')
        try:
            perf_map = {item['label']: float(item['value']) for item in json.loads(perf_json)}
            yr1 = perf_map.get('1 Yr')
            yr3 = perf_map.get('3 Yr')
            yr5 = perf_map.get('5 Yr')
        except (json.JSONDecodeError, KeyError, ValueError):
            pass

    # -- risk (img alt in risk-rte section) --
    risk = None
    rm = re.search(r'risk-rte.*?<img\s+alt="([^"]+)"', html, re.DOTALL | re.IGNORECASE)
    if rm:
        risk = rm.group(1).strip().title()

    # -- fund type / category --
    fund_type = _title_value(html, 'Category')

    # -- minimum investment --
    min_inv = None
    mi = _title_value(html, 'Minimum Investment')
    if mi:
        min_inv = re.sub(r'[^\d.]', '', mi) or None

    if name is None and nav is None:
        return None

    return {
        "fund_code": fund_code,
        "name": name,
        "nav": nav,
        "mer": mer,
        "1yr": yr1,
        "3yr": yr3,
        "5yr": yr5,
        "distribution": None,
        "risk": risk,
        "fund_type": fund_type,
        "account_eligibility": None,
        "minimum_investment": min_inv,
    }


